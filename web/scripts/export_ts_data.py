def export_t5_vocab(out_path: str) -> None:
    model_file = os.path.join(ROOT_DIR, "t5_spiece.model")
    sp = spm.SentencePieceProcessor(model_file=model_file)
    vocab = [[sp.id_to_piece(i), round(sp.get_score(i), 3)] for i in range(sp.get_piece_size())]
    raw = json.dumps(vocab, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    gz = gzip.compress(raw, compresslevel=9)
    b64 = base64.b64encode(gz).decode("ascii")

    content = (
        "// AUTO-GENERATED compressed T5 SentencePiece Unigram table from t5_spiece.model\n"
        f"// Vocab pieces: {len(vocab)}, raw JSON: {len(raw)} bytes, gzip: {len(gz)} bytes, base64: {len(b64)} chars\n"
        f'export const T5_VOCAB_GZIP_B64 = "{b64}";\n'
    )
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"Exported T5 vocab ({round(len(b64)/1024, 1)} KB base64) to {out_path}")


